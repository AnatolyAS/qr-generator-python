def gf_add(x: int, y: int) -> int:
    """Сложение в поле Галуа (XOR)."""
    return x ^ y


def gf_mult(x: int, y: int) -> int:
    """Умножение в поле Галуа GF(256) через таблицы EXP/LOG."""
    if x == 0 or y == 0:
        return 0
    return EXP_TABLE[(LOG_TABLE[x] + LOG_TABLE[y]) % 255]


def gf_poly_scale(p: List[int], x: int) -> List[int]:
    """Умножение полинома на скаляр."""
    return [gf_mult(coef, x) for coef in p]


def gf_poly_add(p: List[int], q: List[int]) -> List[int]:
    """Сложение двух полиномов (XOR коэффициентов)."""
    # Выравниваем длины списков нулями
    if len(p) < len(q):
        p, q = q, p
    q = [0] * (len(p) - len(q)) + q
    return [gf_add(pc, qc) for pc, qc in zip(p, q)]


def gf_poly_mul(p: List[int], q: List[int]) -> List[int]:
    """Умножение двух полиномов."""
    res = [0] * (len(p) + len(q) - 1)
    for j in range(len(q)):
        for i in range(len(p)):
            res[i + j] = gf_add(res[i + j], gf_mult(p[i], q[j]))
    return res


def gf_poly_div(dividend: List[int], divisor: List[int]) -> Tuple[List[int], List[int]]:
    """
    Деление полиномов в поле Галуа.
    Возвращает (частное, остаток).
    Используется для вычисления байтов коррекции.
    """
    msg_out = dividend[:]  # Копируем, чтобы не менять оригинал
    divisor_lead_term = divisor[0]
    divisor_lead_inv = EXP_TABLE[255 - LOG_TABLE[divisor_lead_term]]
    
    for i in range(len(dividend) - (len(divisor) - 1)):
        coef = msg_out[i]
        if coef != 0:
            factor = gf_mult(coef, divisor_lead_inv)
            for j in range(1, len(divisor)):
                if divisor[j] != 0:
                    msg_out[i + j] = gf_add(msg_out[i + j], gf_mult(divisor[j], factor))
    
    separator = -(len(divisor) - 1)
    return msg_out[:separator], msg_out[separator:]


def rs_encode_msg(msg_in: List[int], nsym: int) -> List[int]:
    """
    Алгоритм Рида-Соломона.
    Генерирует nsym байтов коррекции для входного сообщения msg_in.
    
    Args:
        msg_in: Список байтов данных.
        nsym: Количество байтов коррекции (ECC).
        
    Returns:
        Список байтов коррекции.
    """
    if nsym == 0:
        return []
        
    gen = GENERATOR_POLYNOMIALS[nsym]
    
    # Подготавливаем массив: данные + нули для коррекции
    mm = len(msg_in) + nsym

    # Создаем bytearray из нуля длиной nsym
    message_out = msg_in + bytearray(nsym)
    
    # Быстрый синтетический делитель (аналогично gf_poly_div, но оптимизирован)
    for i in range(len(msg_in)):
        coef = message_out[i]
        if coef != 0:
            # Оптимизация: логарифм коэффициента
            lcoef = LOG_TABLE[coef]
            for j in range(1, len(gen)):
                message_out[i + j] ^= EXP_TABLE[(lcoef + LOG_TABLE[gen[j]]) % 255]
                
    # Байты коррекции — это остаток от деления, который остался в конце массива
    return message_out[-nsym:]